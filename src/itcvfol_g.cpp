	lower_thres += (lower_thres - first);	

	/* upper_thres assumed at upper 10% of range */

	upper_thres = last - 0.10 * (last - first); // minus 10% of range

  	pminus = 0.005 * (last - first); 
  	plusminus =  (int) (pminus+0.5);


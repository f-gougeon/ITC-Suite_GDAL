/* Tells whether the first value (a) is between the other two (b,c) */

int between(double a, double b, double c)
{
  if( (c > b) && (a<c) && (a>=b) ) return(TRUE);
  if( (b > c) && (a<b) && (a>=c) ) return(TRUE);
  return(FALSE);
}

/****************************************************************/

/* Tells whether the first value (int a) is close to the second value (int b) */

int close_to(int a, int b)
{

  if(a == b)  return(TRUE);
  if(a == b+1)  return(TRUE);
  if(a == b-1 )  return(TRUE);
  return(FALSE);
}


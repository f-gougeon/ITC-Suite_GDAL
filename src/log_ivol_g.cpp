/* Put a safety border (CLEAR BIT) around a bitmap in order not to fall off the image (section) */
/* Here, the global variable "bmoffset" (a line offset) is used to work on image sections */
/* xsize and ysize are image (or section) sizes in pixels and lines */

void prep_bmp_zero(PixVal *bmp, int xsize, int ysize)
{
  int     i, j;

  // printf( "\nPreparing bitmap safety border ...\n");

/* upper border */

  for (i = 0; i < BORDER; i++)
  for (j = 0; j < xsize; j++) 
	clearbit(bmp, (bmoffset+i) * (int64)xsize + j);

  //fprintf(stdout,"\n Upper border done to line: %d \n", bmoffset+BORDER-1);

/* lower border */

  for (i = ysize - BORDER; i < ysize; i++)
  for (j = 0; j < xsize; j++) 
	clearbit(bmp, (bmoffset+i) * (int64)xsize + j);

  //printf("\n Lower border done at last line: %d at last position %I64d Pixels \n", bmoffset+ysize,(bmoffset+ysize)*(int64)xsize); 

  for (i = 0; i < ysize; i++) 
  { 
	  /* left side */
  for (j = 0; j < BORDER; j++)
	clearbit(bmp, (bmoffset+i) * (int64)xsize + j);

	/* right side */
  for (j = xsize - BORDER; j < xsize; j++)
	clearbit(bmp, (bmoffset+i) * (int64)xsize + j);

  }

}


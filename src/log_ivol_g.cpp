		  /* if(y==4257) printf("\nImage line 4257 is cut by vertex %d to %d \n", kk, kk+1); */


		  /* compute X projections of pixel center on that line */ 

		  slope = (tmpVertices[kk+1].y - tmpVertices[kk].y) / (tmpVertices[kk+1].x - tmpVertices[kk].x);

		  /* yp = slope * (xx - tmpVertices[kk].x) + tmpVertices[kk].y; */

		  xp = 1/slope * (yy - tmpVertices[kk].y) + tmpVertices[kk].x;


/* This function processes the confusion sums and generates the confusion matrix with
   percentages.  Also generate the Kappa Coefficient and Kappa Variance.
*/

void process_matrix(void)
{
	int             i, j;
	float          sum_rows[BITMAPS], totavg, totdiag, totrowcol;
	float          t1, t2, t3, t4;

	totsum = totavg = totdiag = totrowcol = 0.0;
	t1 = t2 = t3 = t4 = 0.0;
	/*
	 * Form sums for rows, cols, main diagonal, and grand sum, not
	 * including unclassified
	 */
	for (j = 0; j < nclass; j++) {
		sum_rows[j] = 0.0;
		sum_cols[j] = 0.0;
		totdiag += (float) confusion_matrix[j][j];
		for (i = 0; i < nclass; i++) {
			sum_rows[j] += (float) confusion_matrix[j][i];
			sum_cols[j] += (float) confusion_matrix[i][j];
			totsum += (float) confusion_matrix[j][i];
		}
	}

	/* Generate intermediate values for kappa */
	for (i = 0; i < nclass; i++) {
		totrowcol += (sum_rows[i] * sum_cols[i]);
		t3 += ((float) confusion_matrix[i][i] * (sum_cols[i] + sum_rows[i]));
		for (j = 0; j < nclass; j++)
			t4 += (confusion_matrix[i][j] * pow((sum_cols[j] + sum_rows[i]), 2.0));
	}

	/* Calculate kappa coefficient and kappa variance */
	t1 = totdiag / totsum;
	t2 = totrowcol / (totsum * totsum);
	t3 /= (totsum * totsum);
	t4 /= pow(totsum, 3.0);
	kappa = (t1 - t2) / (1.0 - t2);
	varkappa = (1.0 / totsum) * (((t1 * (1.0 - t1)) / pow((1.0 - t2), 2.0)) +
	((2.0 * (1.0 - t1) * (2.0 * t1 * t2 - t3)) / pow((1.0 - t2), 3.0)) +
				     ((pow((1.0 - t1), 2.0) * (t4 - 4.0 * t2 * t2)) / pow((1.0 - t2), 4.0)));

	/* Update grand total, column totals to include unclassified */
	for (i = 0; i < nclass; i++) {
		totsum += (float) confusion_matrix[nclass][i];
		sum_cols[i] += (float) confusion_matrix[nclass][i];
		totavg += ((float) confusion_matrix[i][i] / sum_cols[i]);
	}

	/* Calculate average accuracy and overall accuracy */
	avgacc = 100.0 * totavg / nclass;
	overacc = 100.0 * totdiag / totsum;
}



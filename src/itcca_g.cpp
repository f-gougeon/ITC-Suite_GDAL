/*
   This function scans the image to find in the masked area (at this point, it 
   is the ANDed version of "a" training area and "an" ITC class bitmap) a minimum  
   2x2 area corresponding to a tree. When found, the ITC is filled (thus erased)
   in that bitmap and in the fuller ITC class bitmap. 
   The tree is then counted in the confusion matrix at proper slot ([xmat][ymat]).
*/

void scan_for_tree_inc(unsigned char *full_bitmap, unsigned char *mask_data, int xmat, int ymat, int xsize, int ysize)
{
  int x, y, count1, count2;
  int64 bitnum;

  for (y = 2; y < ysize; y++)
  for (x = 2; x < xsize; x++) 
    {
    bitnum = (int64)xsize*(y-1) + x-1;  	/*bitnum starting at zero, (x,y) at (1,1) */

    /* check if 2x2 window is 'filled' */
    if ( testbit(mask_data,bitnum) && testbit(mask_data,bitnum+1) &&
           testbit(mask_data,bitnum+xsize) && testbit(mask_data,bitnum+xsize+1)
			   && testbit(full_bitmap,bitnum) )   		// test if ITC not used already (i.e., erased)
	{
	count1 = count2 = 0;
	fill(x, y, xsize, full_bitmap, &count1);
	fill(x, y, xsize, mask_data, &count2);
	confusion_matrix[xmat][ymat]++;
	if (xmat == ymat) pix_count[xmat] += count1;	/* for crown area of OK ITC */
	}
    }
}
 

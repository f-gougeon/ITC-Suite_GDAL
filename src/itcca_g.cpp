/* 
   This function 'fills' a tree shape, gathering information on the tree size and
   REMOVING it from the mask bitmap during processing
*/

void fill(int x, int y, int xsize, unsigned char *mask_data, int *count)
  {
  int64 bitnum;
  bitnum = (int64)xsize*(y-1) + x-1; 	/* bitnum starts at zero, (x,y) at (1,1) */
  (*count)++; 			    	/* increase count to get crown area */
  clearbit(mask_data,bitnum);		/* turn off bit */
  if (testbit(ext_mask,bitnum)) PointMet++;	/* pointer(s) encountered in POINTS mode */

  /* Fill recursively starting at current position */

  if (testbit(mask_data,bitnum+1))	fill(x+1, y, xsize, mask_data, count);
  if (testbit(mask_data,bitnum-xsize))	fill(x, y-1, xsize, mask_data, count);
  if (testbit(mask_data,bitnum-1))	fill(x-1, y, xsize, mask_data, count);
  if (testbit(mask_data,bitnum+xsize))	fill(x, y+1, xsize, mask_data, count);
  }


/**************************************************************/

/* This function 'fills' a tree crown, gathering information on the crown size
 and center of gravity and removing it from the bitmap while processing
*/

void fill_cg(int x, int y, int xsize, unsigned char *crown_data, int *count)
  {
  int64 bitnum;

  bitnum = (int64)xsize*(y - 1) + x-1;   	 /*bitnum starting at zero */
  (*count)++; 				/* increase count to get crown area */

  sum_x = sum_x + x;
  sum_y = sum_y + y;

  /* turn off bit & fill recursively starting at current position */

  clearbit(crown_data,bitnum);
  if (testbit(crown_data,bitnum+1))	fill_cg(x+1, y, xsize, crown_data, count);
  if (testbit(crown_data,bitnum-xsize))	fill_cg(x, y-1, xsize, crown_data, count);
  if (testbit(crown_data,bitnum-1))	fill_cg(x-1, y, xsize, crown_data, count);
  if (testbit(crown_data,bitnum+xsize))	fill_cg(x, y+1, xsize, crown_data, count);
  }


	if( x < pb->xmin ) pb->xmin = x;

	if ( testbit(isolbitbuf, bitnum-Pixels-1) ) 	fill_8c_blob(x-1,y-1,pb);
	if ( testbit(isolbitbuf, bitnum-Pixels) ) 	fill_8c_blob(x,y-1,pb);
	if ( testbit(isolbitbuf, bitnum-Pixels+1) ) 	fill_8c_blob(x+1,y-1,pb);
	if ( testbit(isolbitbuf, bitnum-1) ) 		fill_8c_blob(x-1,y,pb);

/*	This is a function to convert a single forest stand from a vector-form (i.e., a polygon) 
	to a filled bitmap stand (using center of pixel in or out as criteria for pixel in or out)
	*****   SERIOUS MODS in FEB 2013 **** should be faster
*/

void vect2rast(int nVertex, GDBVertex *inVertices, unsigned char *mask_data, int xsize, int hShapeId, int set_flag)
  {
  int ii, jj, kk, kkk, x, y, icount, ipos;
  int64 bitnum;
  float xx, yy, xmin, xmax, ymin, ymax, slope, xp;
  int ixmin, ixmax, iymin, iymax;
  float line_xx[MAX_INTERCEPT], line_xp[MAX_INTERCEPT], n_line_xx[MAX_INTERCEPT], n_line_xp[MAX_INTERCEPT];
  GDBVertex *	tmpVertices;
  
  
  Poly_Outside = 0;	// reset global flag about polygon being outside image area


/* Convert geographic coordinates to image coordinates (all vectors of poly) */

  tmpVertices = (GDBVertex *) malloc(nVertex * sizeof(GDBVertex));

  for (kk = 0; kk < nVertex; kk++)
    {
    tmpVertices[kk].x = (inVertices[kk].x - topleftX) / transformX ;
    tmpVertices[kk].y = (inVertices[kk].y - topleftY) / transformY ;
    }


// FOR DEBUG - print vertices in image coordinates

//  fprintf(stdout,"In vect2rast() - Printing some vertices in image coordiantes\n");

//  for (kk=0; kk<nVertex; kk++)
/*
  for (kk=0; kk<12; kk++)
    {
    fprintf(stdout," %d = %8.2f,%8.2f ", kk+1, tmpVertices[kk].x, tmpVertices[kk].y);
    if ( ((kk+1)/4)*4 == (kk+1) ) fprintf(stdout,"\n");
    }
  fprintf(stdout,"\n");
*/

  /* gather x and y minimums and maximums positions of polygon (i.e. bounding square) */

  xmin = xmax = tmpVertices[0].x;
  ymin = ymax = tmpVertices[0].y;

  for (kk=1; kk< nVertex; kk++)
    {
    if (xmax < tmpVertices[kk].x) xmax = tmpVertices[kk].x;
    if (xmin > tmpVertices[kk].x) xmin = tmpVertices[kk].x;
    if (ymax < tmpVertices[kk].y) ymax = tmpVertices[kk].y;
    if (ymin > tmpVertices[kk].y) ymin = tmpVertices[kk].y;
    }

  ixmin = (int) (xmin); iymin = (int) (ymin);	/* round-off on generous side (outside area)*/
  ixmax = (int) (xmax+1); iymax = (int) (ymax+1);

  xcg = (int) (0.5 + (xmax + xmin)/2);	
  ycg = (int) (0.5 + (ymax+ymin)/2);   /* approx center of grav. */


 //   printf("\n Area of interest: xmin,ymin,xmax,ymax = %8.2f,%8.2f,%8.2f,%8.2f\n", xmin,ymin,xmax,ymax); 

//    printf("Area of interest xmin,ymin,xmax,ymax,xcg,ycg = %d  %d  %d  %d  %d  %d\n\n", ixmin,iymin,ixmax,iymax,xcg,ycg); 	
 
/* Disregard this polygon if part of it are outside the image */
 
  if ( (ixmin < 1) || (iymin < 1) || (ixmax > Pixels) || (iymax > Lines) )
	{
	fprintf(stdout,"\n*NOTE*: A part of this polygon is outside the image area.\n");
	fprintf(stdout,"*NOTE*: This polygon will be DISREGARDED in reporting CWD/LOG info.\n");
	Poly_Outside = 1;
	//HFree(tmpVertices);
	return;
	}

/*
		SCAN (line by line) the square area delimited by xmin,xmax,ymin,ymax 
*/

    for(y = iymin; y <= iymax; y++)		/* for each image line of that bounding square */
      {
      icount = 0;
	  yy = (float) y - 0.5;

	/* for the given polygon, check witch line segment intercepts that image line */

	  kkk=0;
	  for (kk=0; kk < (nVertex-1); kk++)	/* for all vertices of polygon */
	    {
	    /* bypass invisible ring connectors  */
	    if ( RingFlag2 && (kk == (RingStart[kkk]-1) ) ) {kk++; kkk++;} 

 	    if ( between(yy,tmpVertices[kk].y,tmpVertices[kk+1].y) )
		  {
		  /* if(y==4257) printf("\nImage line 4257 is cut by vertex %d to %d \n", kk, kk+1); */


		  /* compute X projections of pixel center on that line */ 

		  slope = (tmpVertices[kk+1].y - tmpVertices[kk].y) / (tmpVertices[kk+1].x - tmpVertices[kk].x);

		  /* yp = slope * (xx - tmpVertices[kk].x) + tmpVertices[kk].y; */

		  xp = 1/slope * (yy - tmpVertices[kk].y) + tmpVertices[kk].x;

		  /* if ( y>4250 && y<4260)
			   fprintf(stdout,"\nFor image line = %d  and xp = %8.3f using vector %d,%d \n",y,xp,kk+1,kk+2); */

		  line_xp[icount] = xp;
		  icount++;

		  }	/* end of if between vertices */

	     }	/* end of vertices scanning */

	  /* if( y>4250 && y<4260) fprintf(stdout,"\t For line %d, icount = %d \n", y, icount); */

	if ( icount > MAX_INTERCEPT) 
	  {
	  fprintf(stderr,"\n ### ERROR ### (in vect2ras) \n");
	  fprintf(stderr,"\n Shape %d intercepts an image line %d MORE THAN %d times\n", hShapeId, y, MAX_INTERCEPT);
	  fprintf(stderr,"\n Shape may have a flat line that too long for the software \n\n");
	  exit(-1); 
	  }

	// fprintf(stdout,"\t For line %d, icount = %d \n", y, icount);

	if ( icount == 1) 
	  {
	  fprintf(stdout,"\n ### ERROR ### (in vect2ras) \n");
	  fprintf(stderr,"\tMay have singular point in shape %d \r",hShapeId);
	  fprintf(stdout,"\n OR shape %d in shp layer may not be a closed shape.\n", hShapeId);

	  fprintf(stdout,"\n Start and End X coordinates: %f and %f \n", 
					tmpVertices[0].x,tmpVertices[nVertex-1].x);
	  fprintf(stdout,"\n Start and End Y coordinates: %f and %f \n", 
					tmpVertices[0].y,tmpVertices[nVertex-1].y);
	  exit(-1); 
	  }

/* sort intersection info by increasing xp coordinates */

	for (jj = 0; jj<icount; jj++)
	  {
          xmin = line_xp[0]; ipos = 0;
	  for (ii = 1; ii<icount; ii++) { if (line_xp[ii] < xmin) { xmin = line_xp[ii]; ipos = ii; } }
	  n_line_xp[jj] = line_xp[ipos];
	  line_xp[ipos] = 100000;	/* arbitrary big number for item not to be used */
	  }



/*
	fprintf(stdout,"\t Sort is done \n");
	for (jj = 0; jj<icount; jj++) fprintf(stdout,"\t %f ", n_line_xp[jj]);
	fprintf(stdout,"\n");
*/


/*	Fill between pairs of line intersections.
	Only use the pixel itself ((int)+1) if center of pixel is inside the crown,
	otherwise use the next inside pixel.
	This is implemented via +1.5 on the left and +0.5 on the right.
*/

     for (jj = 0; jj<icount; jj+=2)
	{
	x = (int) (n_line_xp[jj] + 1.5);		/* initial pixel position */
	while( x <= ((int)(n_line_xp[jj+1] + 0.5)) )	/* paint line until next intersection */
	  {
	  bitnum = ((int64)xsize*(y-1)) + x-1;
	  if(set_flag) 
		{ setbit(mask_data,bitnum); shp_area++; }
	  else
		{ clearbit(mask_data,bitnum); shp_area--; }

	  x++;
	  }
	}

     }		/* end of for each line */


/* FOR DEGUGGING 

  fprintf(stdout,"\nRasterized tree crown: \n");
  fprintf(stdout," Covers area xmin,xmax,ymin,ymax = %d,%d,%d,%d\n", ixmin,ixmax,iymin,iymax);

  for(i = iymin; i <= iymax; i++)
   {
    for(j = ixmin; j <= ixmax; j++)
	{
	bitnum = ((int64)xsize*(i-1)) + j-1;
	fprintf(stdout," ");
	if(testbit(mask_data,bitnum)) fprintf(stdout,"X");
	else  fprintf(stdout,".");
	}
   fprintf(stdout,"\n");
   }
   fprintf(stdout,"\n");
*/
	 
  //HFree(tmpVertices);

  /* fprintf(stdout,"Getting out of vect2rast() for shape: %d \n",hShapeId); */

  }	/* end of function */




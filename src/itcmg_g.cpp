/* This function 'fills' a tree shape, gathering information for processing.
	NOTE:	The ITC gets removed from the  bitmap while processing
*/

void fill(int x, int y, int xsize, unsigned char *bitmap, tree_node *tree_info, int option)

  {
  int64 bitnum, bytenum;

  bitnum = (y-1)*(int64)xsize + x-1;			/* position in full bitmap */
  bytenum = ((y-1) - imaoffset)*(int64)xsize + x-1; 	 /* position in image section */

  //fprintf(stdout,"bitnum, bytenum, option : %I64d %I64d %d\t",bitnum, bytenum, option);
  //fprintf(stdout,"minpos, maxpos: %I64d %I64d\t",minpos, maxpos);

  /* if one pixel is outside image section --> abort the fill & grab other image section*/

  if  (bitnum > maxpos)  { next_sect=1; return; }

  if  (bitnum > minpos)  
	process_image_data(bytenum, bitnum, tree_info, option);

  /* turn off bit & fill recursively starting at current position */

  clearbit(bitmap,bitnum);

  if (testbit(bitmap,bitnum+1))
		fill(x + 1, y, xsize, bitmap, tree_info, option);
  if (testbit(bitmap,bitnum-xsize))
		fill(x, y - 1, xsize, bitmap, tree_info, option);
  if (testbit(bitmap,bitnum-1))
		fill(x - 1, y, xsize, bitmap, tree_info, option);
  if (testbit(bitmap,bitnum+xsize))
		fill(x, y + 1, xsize, bitmap, tree_info, option);	

  }

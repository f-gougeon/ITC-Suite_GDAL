/* This function scans the given bitmap to find trees.  A 2x2 window moves across, starting
   in the upper left and working across, then down to the lower right.  If all bits in the
   2x2 window are 'filled' then a tree has been found and fill() is called to gather the
   information needed to generate the mask type.  This information is stored in
   a tree node for that tree.
*/

void scan_for_tree(int xsize, int ysize, PixVal * bitmap, int option)
  {
	int             x, y;
	int64		bitnum;
	tree_node      *new_tree;

	printf("\nScan_for_tree() started ... \n\n");
	//printf("\n xsize, ysize, option : %d %d %d \n",xsize, ysize, option);
	//printf("\n minpos, maxpos : %I64d %I64d  \n", minpos, maxpos );

	for (y = 2; y < ysize-1; y++)
	{
	for (x = 2; x < xsize-1; x++)
	  {
	  bitnum = (y-1)*(int64)xsize + x-1;		// position in image in pixels (bits or bytes)

	  if (bitnum < minpos) continue;		// skip irrelevant image parts (when by sections) 

	  if (bitnum+xsize+1 > maxpos)			// if at max pos in that section
		{
		printf("\nStopping scan at position: %I64d \n", maxpos);
		retposy=y; retposx=x;
		next_sect = 1;			// call for next section
		return;
		}


          /* detect an ITC -- check if 2x2 window is 'filled' */

	  if ( testbit(bitmap,bitnum) && testbit(bitmap,bitnum+1) &&
		testbit(bitmap,bitnum+xsize) && testbit(bitmap,bitnum+xsize+1) )
	    {
	        //printf("\n\nBlob found at %d %d \n", x,y);

	        new_tree = new_tree_node();

		fill(x, y, xsize, bitmap, new_tree, ILLUM_AVG);		// First fill() to get ITC average greylevel and count 
       		//printf("\nITC Count=%d\n",  new_tree->count);	

		if(next_sect) { retposy=y; retposx=x; return; }		// fill() may have returned a flag to go next section
		
		 /* If we have a tree */
		
		 if (new_tree->count != 0) 
			  {
			  new_tree->image_avg = new_tree->image_sum / new_tree->count;		/* calculate its average grey level from sum */
			  new_tree->count = 0;						/* reset some value for next fill() */
			  new_tree->image_sum = 0;
			  }
	        //printf("\n\n2nd fill() at %d %d \n", x,y);

		fill(x, y, xsize, tempbitbuf, new_tree, option);		/* 2nd fill() to do operation like LIT */

	        //fprintf(stdout,"Lit/Shade/Top Count=%d\n",  new_tree->count);

		if ((option == TOP_MASK) && (new_tree->count != 0)) setbit(maskbitbuf,new_tree->tt_pos); 

		free(new_tree);

	    } 	/* End of if */

	  }	// end of "for x"

 		printf("%d lines done\r", y);

	  if ( (y/100)*100 == y)  printf("%d lines done\r", y);

   	}	/* End of main loop */

	printf("%d lines done\n\n", y);
	retposy=y;  retposx=x;
	next_sect = 0;

	//printf("\nScan_for_tree() Done \n");
  }





/* This function performs the appropriate processing operation, depending on the
   type of mask specified (given by option).
*/

void process_image_data(int64 bytenum, int64 bitnum, tree_node *tree_info, int option)
{
	int32 pix_val;		// to get pixel grey-level from image

	//printf("\nGOT IN process_image_data()\n");

	pix_val = (*get_pix_val) (illum_ima, bytenum);	//works with get_pix_val = get_u8 or get_pix_val = get_u16
							// works with setting in itc_io_g & define in itc_io_g.h
	//pix_val = (*get_u8) (illum_ima, bytenum);		// works "as is" for 8b images
	//pix_val =  get_u8(illum_ima, bytenum);		// works if function get_u8() is in program

	//printf("\n Pixel value : %d \n", pix_val );

	switch (option) 
	{
		case LIT_MASK:
			if (pix_val > tree_info->image_avg) { setbit(maskbitbuf, bitnum);(tree_info->count)++; }
		break;
		case SHADE_MASK:
			if (pix_val <= tree_info->image_avg) { setbit(maskbitbuf,bitnum); (tree_info->count)++; }	
		break;
		case TOP_MASK:
			(tree_info->count)++;
			if (tree_info->crown_max <= pix_val) 
					{tree_info->crown_max = pix_val; tree_info->tt_pos = bitnum;}
		break;
		case ILLUM_AVG:
			(tree_info->count)++;
			tree_info->image_sum += pix_val;
		break;

		default:
			(tree_info->count)++;
			if (tree_info->crown_max <= pix_val) 
				{tree_info->crown_max = pix_val; tree_info->tt_pos = bitnum;}
		break;
	}
}




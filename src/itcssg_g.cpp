/* This function processes the current list of trees for a species, generating a
   covariance matrix and a correlation matrix for that species.
	i.e.,	What ever features are picked up for an ITC, the cov. matrix
		reflects the variation of these features (e.g., ITC(MEAN+TEXTURE) )

N.B.:	 Although, the covariance matrix is calculated here in a triangular form 
	(and also used later by the "eigens.c" procedure in a triangular form),
	presently, both matrices are stored in the structure using a full matrix format. 
*/

void species_correl_covar(result_node *species, tree_node *tree_list)
{

	int             i, j, k, ii, kk, n,count;
	float 			pp[CHANNELS*3];
	tree_node       *p;
	float          sum1, sum2, sumsquare1, sumsquare2, product1;
	float          sumofsquares1, sumofsquares2, sumofproducts, correlcoef, covariance;


/*	fprintf(Report,"\n Calculating species covariance and correlation matrices \n"); */

	n = species->number;

	for (i = 0; i < spa_size; i++)
		for (j = i; j < spa_size; j++) 
			{
			sum1 = sum2 = sumsquare1 = sumsquare2 = product1 = 0.0;
			p = tree_list->next_tree;
			count = 0;
			while (p) 
			  {

			  /* for each ITC, organize parameter vector */

				kk=0;
				for (ii = 0; ii < nsigtypes; ii++) 
				  {
				  for(k=0; k<ibufs; k++)		/* for n channels */
				    {
				    if (st[ii] == MEAN) pp[kk+k]= p->itc_mean[k];
				    if ( (st[ii] == TCL) || (st[ii] == TCL2) ) 
				      {
				      pp[kk+k]= p->intercept[k];
				      pp[kk+ibufs+k]= p->eigvector[k];
				      }
				    if (st[ii] == TCL2) pp[kk+ibufs*2+k]= p->eigvalues[k];
				    }
				/* texture and structure signature are now only from 1st channel */
				    if (st[ii] == TEXTUR) pp[kk]= p->variance[0];
			   	    if (st[ii] == STRUCT) 
				      {
				      pp[kk]= p->structure_param[0];
				      pp[kk+1]= p->structure_param[ibufs];
				      }
				  /* kk = kk + ibufs*sign_dim_mul[st[ii]] ;*/
				  kk = kk + sign_dim_mul[st[ii]]; 
				  }

	/*		for(k=0; k<(3*ibufs); k++)fprintf(stdout," %7.2f ",pp[k]); */
	/*		fprintf(stdout,"\n"); */

			/* accumulate sums and sums of squares */

				sum1 += pp[i];
				sum2 += pp[j];
				sumsquare1 += ( pp[i] * pp[i] );
				sumsquare2 += ( pp[j] * pp[j] );
				product1   += ( pp[i] * pp[j] );
				count ++;
				p = p->next_tree;
			  }
	/*	fprintf(stdout,"\nCOUNT for species: %d \n", count); */
	/*	fprintf(stdout,"\n\n"); */

			/* Calculate species covariance (corr.) matrix for given parameters */

			sumofsquares1 = sumsquare1 - (sum1 * sum1) / n;
			sumofsquares2 = sumsquare2 - (sum2 * sum2) / n;
			sumofproducts = product1 - (sum1 * sum2) / n;
			covariance = sumofproducts / (n - 1);
			correlcoef = sumofproducts / sqrt(sumofsquares1 * sumofsquares2);

/*  fprintf(stdout,"\n sum1,sum2,product1,covariance: %f %f %f %f \n", 
						sum1,sum2,product1,covariance); */

			/* Form correlation and covariance matrices (full square matrices)*/

			species->correlation[i * spa_size + j] = correlcoef;
			species->correlation[j * spa_size + i] = correlcoef;
			species->covariance[i * spa_size + j] = covariance;
			species->covariance[j * spa_size + i] = covariance;
			}
}



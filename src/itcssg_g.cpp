/*	This function 'fills' a tree crown (an ISOL (i.e., an ITC, a tree cluster or a blob)),  
	gathering pixel values in a list for later processing of species signature.
	(N.B.: It removes the crown from the bitmap during the fill)  
	X and Y are FULL image coordinates (as per the PCI dataset file) 
	"bytenum" is (an offset) image position within the present image section
	"bitnum" is bitmap position within the full bitmap (could be >2Gp, thus int64)
*/

void fill_do(int x, int y, int xsize, unsigned char *bitmap, tree_node *tree_info, int option)
  {
  int64 bytenum;
  int64 bitnum;

  /* When functionning by Vectored ITCs (Manvec and slayer), you can go off the image section both ways */
  /* HERE, the "drop_ITC_flag" only signals to delete info accumulate for that ITC (cause partial info) */
  /* The ITC will get redone properly when not on a boundary */

  if ( (by_sections) && (y+1 >= sect_limit) )		{drop_ITC_flag=1; return; }
  if ( (by_sections) && (y-1 <= next_sect_start) )	{drop_ITC_flag=1; return; }

  /* check section boundary issues (dont go off the image section) */

  if (next_sect_flag) return;	 /* for all the other recursions of fill() after below */
  if ( (by_sections) && (y+1 >= sect_limit) )	{next_sect_flag=1; return; }

    /* bitnum (sect_bitnum) starts at zero, but x and y image coordinate start at 1,1  */

 	bitnum = (y-1)*(int64)Pixels + x-1;			/* bitnum within full bitmap */

	bytenum = (y-1-line_offset)*(int64)Pixels + x-1;		/* image position (offset) within present image section */



	(tree_info->count)++;		/* accumulate for crown size*/
	tree_info->xpos += x;		/* accumulate for 2D center of gravity estimation */
	tree_info->ypos += y;

/* 
	IDEA : 
	When using LIT mask (cause good for multispectral classif), also produce a full ITC pixel list (not just LIT-related list)
	as that would be better to use for the STRUCTURE, TCL,and TCL2 signatures (which should work better on a full crown) 
	This way you could combine MSS LIT side signatures with a better structure signature)
*/
 
// Accumulate (in a list) FULL ITC crown-based MSS data one pixel at the time

	process_ITC_image_data(x, y, bytenum, tree_info);


 /* Accumulate crown-based information one pixel at the time (under LIT mask, or pointers if used) */

  if ( (!ExtMaskFlag) || (ExtMaskFlag && (testbit(extmaskbuffer,bitnum))) || (PointsFlag) )

	process_tree_image_data(x, y, bytenum, tree_info);


  if ( testbit(extmaskbuffer,bitnum) ) PointMet++;	/* pointer encountered in POINTS mode */	


/* fill recursively starting at current position */

  clearbit(bitmap,bitnum);		/* turn off bit */
  if (testbit(bitmap,bitnum+1))
	fill_do(x + 1, y, xsize, bitmap, tree_info, option);

  if (testbit(bitmap,bitnum-xsize))
	fill_do(x, y - 1, xsize, bitmap, tree_info, option);

  if (testbit(bitmap,bitnum-1))
	fill_do(x - 1, y, xsize, bitmap, tree_info, option);

  if (testbit(bitmap,bitnum+xsize))
	fill_do(x, y + 1, xsize, bitmap, tree_info, option);

  }	// End of function 


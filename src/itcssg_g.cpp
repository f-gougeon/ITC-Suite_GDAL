/* This function 'paints' a tree crown
*/

void paint(int x, int y, int xsize, unsigned char *crown_data)
  {
  int64 bitnum;
  bitnum = (int64)xsize*(y-1) + x-1;   	 /*bitnum starting at zero */
  setbit(crown_data,bitnum);
  if (!testbit(crown_data,bitnum+1))	 paint(x+1, y, xsize, crown_data);
  if (!testbit(crown_data,bitnum-xsize)) paint(x, y-1, xsize, crown_data);
  if (!testbit(crown_data,bitnum-1))	 paint(x-1, y, xsize, crown_data);
  if (!testbit(crown_data,bitnum+xsize)) paint(x, y+1, xsize, crown_data);
  }



/* This function processes the multi-spectral data within a tree crown 
to produce the PIXEL Variance within the tree crown (an internal texture feature)  */

void process_tree_var(tree_node *tree_sign)
{
	int             n, i;
	float          sumofdiff, mean;
	info_node      *p;

	n = tree_sign->process_count;
	for (i = 0; i < ibufs; i++) 
	    {
		sumofdiff = 0.0;
		mean = tree_sign->itc_mean[i];

		p = Proc_pix_list;

		while (p) 
			{
			sumofdiff += (p->data[i] - mean) * (p->data[i] - mean);
			p = p->next_info;
			}

		if (n > 1)
			tree_sign->variance[i] = sumofdiff / ((float) (n - 1));
		}
}


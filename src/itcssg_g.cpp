/* This function 'fills' a tree crown, gathering information on the crown size
   and removing it from the bitmap while processing (so, can be used
   just to erase a crown or a blob).
*/

void fill_count(int x, int y, int xsize, unsigned char *crown_data, int *count)
  {
  int64 bitnum;
  
  bitnum = (int64)xsize*(y - 1) + x-1;   	 /*bitnum starting at zero */
  (*count)++; 				/* increase count to get crown area */

  /* turn off bit & fill recursively starting at current position */

  clearbit(crown_data,bitnum);

  if (testbit(crown_data,bitnum+1))	fill_count(x+1, y, xsize, crown_data, count);
  if (testbit(crown_data,bitnum-xsize))	fill_count(x, y-1, xsize, crown_data, count);
  if (testbit(crown_data,bitnum-1))	fill_count(x-1, y, xsize, crown_data, count);
  if (testbit(crown_data,bitnum+xsize))	fill_count(x, y+1, xsize, crown_data, count);
  }


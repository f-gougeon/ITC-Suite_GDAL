void process_lit_stdev(tree_node *tree_sign)
{
	int            i, lit_count;
	float          sumofdiff, mean;
	float          itc_mean, lit_mean;
	info_node      *p;

	for (i = 0; i < ibufs; i++) 
	    {
	    sumofdiff = 0.0;
	    lit_count = 0;

            itc_mean = tree_sign->itc_mean[1];
	    lit_mean = tree_sign->lit_mean[i];

	    p = Proc_pix_list;

	    while (p) 
		{
		if(p->data[1] > itc_mean) {sumofdiff += (p->data[i] - lit_mean) * (p->data[i] - lit_mean); lit_count++;}
		p = p->next_info;
		}

	    if (lit_count > 1) tree_sign->lit_stdev[i] = sqrt( sumofdiff / (float)(lit_count - 1) );
		}
}




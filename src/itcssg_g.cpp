/* This function scans the mask bitmap (training area "AND" ISOLs) to find trees.  
   A 2x2 window moves across, starting
   in the upper left and working across, then down to the lower right.  If all bits in the
   2x2 window are 'filled' then a tree has been found and fill_do() is called to gather the
   information needed to generate the signature.  This information is stored (i.e., not removed)
   in a tree node for that tree (for some signatures, only if crown is sizeable enough). 
   
   Crown must have at least 10% (of its crown size) in the test area to count (even in INC mode)
*/

void scan_for_tree_inc(int xsize, int ysize, unsigned char *full_bitmap,
		   unsigned char *mask_data, tree_node *tree_list, int species)
  {
  int             x, y;
  int64             bitnum;
  int             count1;
  tree_node      *new_tree, *previous_tree;
  
  previous_tree = tree_list;
  unusedITC = 0;

  //printf("\nGot into scan_for_tree_inc() \n");

  for (y = 2; y < ysize; y++)		/* X and Y are FULL dataset coordinates */
  for (x = 2; x < xsize; x++)  
	{
 	bitnum = (int64)xsize * (y-1) + x-1;     /* bitnum starting at zero, X and Y at (1,1) */

        /* check if at least 2x2 window is 'filled' INSIDE traning area */

	if ( testbit(mask_data,bitnum) && testbit(mask_data,bitnum+1) &&
	     testbit(mask_data,bitnum+xsize) && testbit(mask_data,bitnum+xsize+1) )
	  {
	  //printf("\nFound a tree in TA at %d %d \n", x, y);
	  new_tree = new_tree_node();		/* a node for each tree signature */
	  Proc_pix_list = NULL;		// List(of raw Process (LIT) data) is created (start with a NULL pointer) 
	  FITC_pix_list = NULL;		/* Full ITC list(of raw data) is created and later deleted */

	  fill_do(x, y, xsize, full_bitmap, new_tree, SIG_GEN);		/* get ITC's MSS data */

	  //printf("\nFilled a tree in TA at %d %d \n", x, y);

	  if (next_sect_flag)
	    {
	    sect_end =  y;
	    fprintf(Report, "\nLast operating line from which the end of image section was hit %d\n", sect_end);
	    repaint_crown(full_bitmap);			 /* repaint crown in bitmap and delete MSS data */
	    free(new_tree);
	    return;
	    }

	  /* count to see how much of the ITC is actually inside the training area */
	  
	  count1 = 0;	
	  fill_count(x, y, xsize, mask_data, &count1);  

	  /* Check conditions for keeping that tree crown */
 	  /*	e.g., sizeable enough for higher level signatures  */

	  if ( (new_tree->process_count == 0) || (count1 < 0.1*new_tree->count) ||
	       ( (eigen_flag || textur_flag || struct_flag) && (new_tree->process_count < ibufs+1) ) )
	    {	
	    process_tree_cleanup(new_tree);		/* delete pixel-based MSS data accumulated for crown */
	    free(new_tree);						/* delete tree information */
	    unusedITC++;
	    }
	  else 		/* keep it and process data */
	    {
	    add_to_tree_list(previous_tree, new_tree);
	    new_tree->xpos /= new_tree->count;	
	    new_tree->ypos /= new_tree->count;
	    process_tree_avg(new_tree);
	    process_tree_var(new_tree);
	    if (eigen_flag) itc_covar_eigen(new_tree); 
	    if (struct_flag) itc_structure(new_tree);
	    previous_tree = new_tree;
	    prev_tree[species] = new_tree;		/* needed to cont. list when working by image sections */
	    process_tree_cleanup(new_tree);		/* delete pixel-based MSS data accumulated for crown */
	    }

	  }		/* end of if 2x2 */

	}		/* end of for full bitmap (database) space */

  sect_end =  y;
  }			/* end of function */



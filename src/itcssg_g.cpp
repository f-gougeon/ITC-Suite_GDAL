/* This function repaints the last crown or partial crown 
that was erased by a fill() or a partial fill() 
It also frees-up the memory */

void repaint_crown(unsigned char *bitmap)
{
	info_node *p, *p1;
	int64 bitnum;
	p = Proc_pix_list;		/* points to last node (of pixel MSS data) */

/* Repaint bitmap and free each MSS data nodes (one per pixel) accumulated for the tree */
	
	while (p) 
	  {
	  p1 = p->next_info;			/* reserve pointer to next node */
	  bitnum = (p->ypos-1)*(int64)Pixels + p->xpos - 1;
	  setbit(bitmap, bitnum);
	  free(p);
	  p = p1;
	  }
	/* printf("An ITC was repainted at image sections boundary \n"); */
}


	for (ii = 0; ii < 3; ii++) if(st[ii]==STRUCT) struct_flag = 1;	

	for (ii = 0; ii < 3; ii++) if(st[ii]==STDEV) stdev_flag = 1;	// special research mode on texture
	for (ii = 0; ii < 3; ii++) if(st[ii]==LITSD) litsd_flag = 1;	





	/* no point having TCL and TCL2 together, just TCL2 */

	if (stype == 32) {stype = 3; fprintf(stdout,"\nSignatures TCL+TCL2 collapsed into TCL2\n"); }
	if (stype == 432){stype = 43; fprintf(stdout,"\nSignatures TCL+TCL2 collapsed into TCL2\n"); }

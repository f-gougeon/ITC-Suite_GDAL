/* This function removes the multispectral pixel data accumulated for 
	a single tree crown, freeing up the memory space (i.e., previous versions 
	of ITCSC were not cleaning-up and thus, could not run on big images without
	running out of memory */

void process_tree_cleanup(tree_node *tree)
{
	info_node *p, *p1;

	p = Proc_pix_list;		/* points to last node (of pixel MSS data) */

// free all process (LIT) MSS data nodes (one per pixel) accumulated for the tree 
	
	while (p) 
	  {
	  p1 = p->next_info;
	  free(p);
	  p = p1;
	  }

// free all full crown MSS data nodes (one per pixel) accumulated for the tree 

	p = FITC_pix_list;

	while (p) 
	  {
	  p1 = p->next_info;
	  free(p);
	  p = p1;
	  }
}

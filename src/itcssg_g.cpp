/* This function processes the current information list(MSS data) for a tree, 
   generating a covariance matrix, a correlation matrix, eigenvalues, 
   eigenvectors, and "colour line" intercepts for that tree.

N.B.:	Although, the covariance matrix is calculated here in a lower triangular form 
	(and also used by the "eigens.c" procedure in a lower triangular form),
	presently, both matrices are stored in the structure using a full matrix format.
 	NOTE: This is different from upper triangular form (dont confuse them)
*/

void itc_covar_eigen(tree_node *tree_info)
{
	info_node      *p;
	int             i, j, n, count;
	float          sum1, sum2, sumsquare1, sumsquare2, product1;
	float          sumofsquares1, sumofsquares2, sumofproducts, correlcoef, covariance;

	for (i = 0; i < (ibufs * ibufs); i++)
		matrix1[i] = 0.0;

	//n = tree_info->process_count;		// could be just lit side
	n = tree_info->ITC_count;		// full ITC list of pixels

	count = 0;

	for (i = 0; i < ibufs; i++)
		for (j = 0; j <= i; j++) 	/* for lower triangular form */
			{
			sum1 = sum2 = sumsquare1 = sumsquare2 = product1 = 0.0;

			//p = Proc_pix_list;
			p = FITC_pix_list;		// Full ITC list of pixel MS values

			/* Calculations */
			while (p) 
				{
				sum1 += p->data[i];
				sum2 += p->data[j];
				sumsquare1 += (p->data[i] * p->data[i]);
				sumsquare2 += (p->data[j] * p->data[j]);
				product1 += (p->data[i] * p->data[j]);
				p = p->next_info;
				}

			/* More calculations */
			sumofsquares1 = sumsquare1 - (sum1 * sum1) / n;
			sumofsquares2 = sumsquare2 - (sum2 * sum2) / n;
			sumofproducts = product1 - (sum1 * sum2) / n;
			correlcoef = sumofproducts / sqrt(sumofsquares1 * sumofsquares2);
			covariance = sumofproducts / (n - 1);

			/* Form correlation and covariance matrices (full square matrices)*/
			tree_info->correlation[i * ibufs + j] = correlcoef;
			tree_info->correlation[j * ibufs + i] = correlcoef;
			tree_info->covariance[i * ibufs + j] = covariance;
			tree_info->covariance[j * ibufs + i] = covariance;
			matrix1[count++] = covariance;	
			/* matrix1[count++] = correlcoef;	 lower triangular form */
			}

	/* generate eigenvalues and eigenvectors for that ITC*/

	eigens(matrix1, tree_info->eigvector, tree_info->eigvalues, ibufs);
	eigvsort(tree_info->eigvector, tree_info->eigvalues, ibufs);

	/* generate intercept for that ITC*/

	itc_intercept(tree_info->eigvector,tree_info->itc_mean,tree_info->intercept,ibufs);

}



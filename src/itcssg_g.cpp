/*
	This function processes the list of tree nodes created for a given training 
	area and purifies the tree list by removing (multispectral) outliers.
*/

void   remove_outliers(tree_node *tree_list, int sp_indx, result_node *r, float nstdev)
{
	tree_node      *p, *prev_goodtree, *bad_tree;
	int             i, tcount, outlier, badtreecount;

	/* Traverse tree list and sum values */

	p = tree_list->next_tree;
	prev_goodtree = tree_list;
	tcount = 0;
	badtreecount = 0;

	while (p) 
	{
	outlier=0;
	/* check for ITCs that are outlier by more than "nstdev" standard deviations */
	  for (i=0; i<ibufs; i++) 
		  {
			if ( ( p->itc_mean[i] > r->mean[i] + nstdev*sqrt(r->variance[i]) ) ||
					( p->itc_mean[i] < r->mean[i] - nstdev*sqrt(r->variance[i]) ) ) outlier=1;
		  }

	  if(outlier) {bad_tree = p; badtreecount++; goto Next_tree;}		/* bypass outlier in signature generation */

	  tcount++;
	  prev_goodtree = p;		/* this is the latest good tree */

Next_tree:

		p = p->next_tree;				/* go to next tree in original list */
		
		prev_goodtree->next_tree = p;	/* make sure the previous tree also points there in order 
										to bypass this outlier one in the list */
		if(outlier) free(bad_tree);

	}		/* end of while (p) */


	//printf("\nCount=%d Removed=%d for species %d \n", tcount, badtreecount, sp_indx);

	filteredITC = badtreecount;

	return;

}		/* end of remove_outliers */


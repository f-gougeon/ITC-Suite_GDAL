/* This function expand parameter vector that contain ranges (e.g., 1,-4)
	in_vect		input segment(channel) list possibly including ranges
	out_vect	output expanded list of segments (channels) ## must be different from in_vect
	in_count	number of item in input list
	out_count	number of item in output list
*/
void param_expand(int in_count, int *in_vect,  int *out_vect, int *out_count)
{
	int ii, jj, kk;
	
	for(ii=0; ii<BITMAPS; ii++) out_vect[ii]=0;		// zero output vector for good measure
	
	if(in_count == 0)  { *out_count = 0; return; }

	if(in_vect[0] < 0)
	  	{ fprintf(stderr,"\n##### ERROR - A neg.# can not be the first item of range.\n"); exit(-1); }
	kk=0;
	for (ii = 0; ii < in_count; ii++)
	  {
	  if(in_vect[ii] == 0) 
	  	{ fprintf(stderr,"\n##### ERROR - Segment(channel) number can not be zero \n"); exit(-1); }
	  if(in_vect[ii] > 0) 		//pass through singular items
	  	{ out_vect[kk] = in_vect[ii]; kk++; }
	  if( (in_vect[ii] < 0) && (abs(in_vect[ii]) <= in_vect[ii-1]) )
	  	{ fprintf(stderr,"\n##### ERROR - Range appears to be unacceptable.\n"); exit(-1); }
	  if(in_vect[ii] < 0) 
	    {
	    if ( (abs(in_vect[ii]+in_vect[ii-1]) + kk) > BITMAPS )
	  	{fprintf(stderr,"\n##### ERROR - Expanded list is limited to %d segments.\n",BITMAPS); exit(-1); }

	    for(jj=0; jj<(abs(in_vect[ii]+in_vect[ii-1])); jj++) 
	    		{ out_vect[kk] = out_vect[kk-1] + 1; kk++; }
	    }
	  }
	*out_count = kk;

}	/* end of function */


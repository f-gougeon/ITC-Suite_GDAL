/* This function converts a string where items are separated by commas, spaces,
   or pluses, to items  separated by nulls */

void separate(char *c)
{
	while (*c != '\0') 
	  {
	  if ( (*c == ',')||(*c == ' ')||(*c == '+') ) *c = '\0';
	  c++;
	  }
}



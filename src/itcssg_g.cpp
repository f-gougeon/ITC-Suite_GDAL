	sign_dim_mul[2] = 2*ibufs;		/* TCL takes 2*ibufs dimensions */
	sign_dim_mul[3] = 3*ibufs;		/* TCL2 takes 3*ibufs dimensions */ 
		/* no point doing the following (TEXTURE and STRUCTURE) for all channels */
	sign_dim_mul[4] = 1;			/* now, TEXTURE takes only one dimension (was ibufs)*/
	sign_dim_mul[5] = 2;			/* now STRUCTURE take only two dimensions */

	sign_dim_mul[6] = ibufs;		/* STDEV takes ibufs dimensions */
	sign_dim_mul[7] = 2*ibufs;		/* LITSD takes 2*ibufs dimensions */

	/* WAS spa_size = ibufs*sign_dim_mul[st1] + ibufs*sign_dim_mul[st2] + ibufs*sign_dim_mul[st3]; */

	spa_size = sign_dim_mul[st1] + sign_dim_mul[st2] + sign_dim_mul[st3];


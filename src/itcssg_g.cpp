/* This function allocates memory for a new tree node and initializes the node */

tree_node  *new_tree_node(void)
{
	int             i, j;
	tree_node      *tree;

	tree = (tree_node *) CPLMalloc((unsigned) sizeof(tree_node));
	check_mem(tree);

	/* Initialize fields to zero */

	tree->xpos = 0;	
	tree->ypos = 0;
	tree->count = 0;		/* number of pixel found in the ITC */
	tree->process_count = 0;	/* effective pixels (e.g., LIT pixels */
	tree->ITC_count = 0;
	tree->shapeid = -1;

	for (i = 0; i < CHANNELS; i++) 
	  	{
		tree->itc_mean[i] = 0.0;
		tree->Fitc_mean[i] = 0.0;
		tree->variance[i] = 0.0;
		tree->intercept[i] = 0.0;
		tree->eigvalues[i] = 0.0;

		for (j = 0; j < CHANNELS; j++) {
			tree->eigvector[i * CHANNELS + j] = 0.0;
			tree->correlation[i * CHANNELS + j] = 0.0;
			tree->covariance[i * CHANNELS + j] = 0.0;
			}
		}

	for (i = 0; i < CHANNELS*2; i++) tree->structure_param[i] = 0.0;

	for (i = 0; i < CHANNELS; i++)	{ tree->lit_mean[i] = 0.0; }
	for (i = 0; i < CHANNELS; i++)	{ tree->lit_stdev[i] = 0.0; }


	tree->next_tree = NULL;

	return (tree);
}



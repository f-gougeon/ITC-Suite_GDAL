/* This function processes the multi-spectral data list of a FULL tree crown (EXTBIT not used)
to produce the multi-spectral mean value of the "so-called" LIT side of the crown */
 

/* In the normal mode, LIT side info is produced on its own by using EXTBIT
NORMALLY, producing a lit signature is independent of producing a full crown signature.
HERE, for research purposes, we wanted the full crown MSS means and st.dev. (STDEV mode)
as well as the LIT MSS mean and st.dev. (LITSD mode) at the same time 
for thousands of manually delineated trees (polygons) */

void process_lit_avg(tree_node *tree_sign)
{
	int            i, lit_count;
	float          itc_mean, lit_mean;
	info_node      *p;

	for (i = 0; i < ibufs; i++) 		/* for each multispectral channel */
	    {
            lit_mean = 0.0;
	    lit_count = 0;
            itc_mean = tree_sign->itc_mean[0]; 		/* assumes first band is ILLUMIN ch (FAVed NIR */

            p = Proc_pix_list;	/* for each pixel in the tree crown */

            while (p)
		{
		if(p->data[0] > (int) itc_mean) {lit_mean += (p->data[i]); lit_count++;}			
		p = p->next_info;
		}
            tree_sign->lit_mean[i] = lit_mean / lit_count;
            }
         tree_sign->lit_count = lit_count;
}

